"""Package the approved MiaoZip PNG master as Windows assets (requires Pillow).

The master is artwork, not generated by this script. Keep Assets/MiaoZip.png
when rebuilding. --check validates the checked-in assets without writing files.
"""
from pathlib import Path
import argparse
import io
import struct
from PIL import Image

root = Path(__file__).resolve().parent.parent
assets = root / 'Assets'
target = assets / 'MiaoZipPackageAssets'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
sizes = (16, 20, 24, 32, 40, 48, 64, 96, 128, 256)
budget = 204800

with Image.open(assets / 'MiaoZip.png') as source:
    master = source.convert('RGBA')
assert master.width == master.height and master.getpixel((0, 0))[3] == 0
templates = list((assets / 'PreviewPackageAssets').glob('*.png'))
assert templates, 'Missing package dimension templates'


def png(width, height, limit=None):
    canvas = Image.new('RGBA', (width, height))
    side = min(width, height)
    canvas.alpha_composite(master.resize((side, side), Image.Resampling.LANCZOS),
                           ((width - side) // 2, (height - side) // 2))
    output = io.BytesIO()
    canvas.save(output, format='PNG', optimize=True)
    data = output.getvalue()
    if limit and len(data) > limit:
        for colors in (256, 128, 64, 32):
            indexed = canvas.quantize(colors=colors, method=Image.Quantize.FASTOCTREE)
            output = io.BytesIO()
            indexed.save(output, format='PNG', optimize=True)
            data = output.getvalue()
            if len(data) <= limit:
                break
        assert len(data) <= limit, 'PNG exceeds Windows manifest image budget'
    return data


if not args.check:
    target.mkdir(exist_ok=True)
    for template in templates:
        with Image.open(template) as original:
            (target / template.name).write_bytes(png(*original.size, limit=budget))
    frames = [png(size, size) for size in sizes]
    offset = 6 + len(sizes) * 16
    icon = bytearray(struct.pack('<HHH', 0, 1, len(sizes)))
    for size, frame in zip(sizes, frames):
        dimension = size if size < 256 else 0
        icon.extend(struct.pack('<BBBBHHII', dimension, dimension, 0, 0,
                                1, 32, len(frame), offset))
        offset += len(frame)
    for frame in frames:
        icon.extend(frame)
    (assets / 'MiaoZip.ico').write_bytes(icon)
    (assets / 'MiaoZip.svg').write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
        'viewBox="0 0 1024 1024"><image href="MiaoZip.png" width="1024" '
        'height="1024"/></svg>\n', encoding='utf-8')

for template in templates:
    path = target / template.name
    with Image.open(template) as original, Image.open(path) as image:
        assert image.size == original.size, path.name
        assert image.convert('RGBA').getpixel((0, 0))[3] == 0, path.name
        assert path.stat().st_size <= budget, path.name
with Image.open(assets / 'MiaoZip.ico') as icon:
    assert set(icon.ico.sizes()) == {(size, size) for size in sizes}
print(f'Validated {len(templates)} package assets and {len(sizes)} ICO sizes. Master preserved.')
